_DICTS = {'de': _DE, 'en': _EN}


def detect_lang():
    """'de' when Windows runs in German, else 'en'."""
    try:
        name = (locale.getlocale()[0] or '').lower()
    except Exception:
        name = ''
    return 'de' if name.startswith(('de', 'german')) else 'en'


def set_lang(code):
    global _lang
    _lang = code if code in _DICTS else 'en'


def get_lang():
    return _lang


def t(key, **fmt):
    # n == 1 takes the '<key>.one' text when there is one (4.0.2)
    if fmt.get('n') == 1 and key + '.one' in _EN:
        key += '.one'
    text = _DICTS[_lang].get(key)
    if text is None:
        text = _EN.get(key, key)
    return text.format(**fmt) if fmt else text
